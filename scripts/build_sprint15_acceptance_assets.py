"""Arma evidencia P1 y hoja A4; nunca aprueba máscaras."""

from pathlib import Path
import json
import shutil
import sys

from PIL import Image, ImageDraw, ImageFont
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "artifacts/sticker-studio-sprint15"
P1 = OUT / "p1-human-review"


def background(image, color):
    page = Image.new("RGBA", image.size, color + (255,)); page.alpha_composite(image)
    return page.convert("RGB")


def p1_case(name, original, auto_mask, candidate_mask, final_png, cut):
    folder = P1 / name; folder.mkdir(parents=True, exist_ok=True)
    paths = {"original": original, "automatic_mask": auto_mask,
             "corrected_mask_candidate_unapproved": candidate_mask,
             "final_png_candidate_unapproved": final_png, "cut_contour": cut}
    for label, source in paths.items():
        shutil.copyfile(source, folder / f"{label}{source.suffix}")
    with Image.open(final_png) as opened: rgba = opened.convert("RGBA")
    for label, color in (("white", (255,255,255)), ("black", (0,0,0)), ("magenta", (255,0,170))):
        background(rgba, color).save(folder / f"on_{label}.png")
    (folder / "STATUS.txt").write_text(
        "AUTOMATIC_MASK: generated by pipeline\nCORRECTED_MASK: CANDIDATE - NOT HUMAN APPROVED\n"
        "FINAL_PNG: CANDIDATE - NOT PRODUCTION APPROVED\n", encoding="utf-8")
    return {key: str(folder / f"{key}{source.suffix}") for key, source in paths.items()}


def build_pdf(stickers):
    output = ROOT / "output/pdf/sticker_studio_sprint15_a4_physical_validation.pdf"
    output.parent.mkdir(parents=True, exist_ok=True)
    c = canvas.Canvas(str(output), pagesize=A4, pageCompression=1)
    width, height = A4
    c.setTitle("Doccione Sticker Studio 2.0 - Validacion fisica")
    c.setFont("Helvetica-Bold", 14); c.drawString(12*mm, height-14*mm, "DOCCIONE - HOJA A4 DE VALIDACION FISICA")
    c.setFont("Helvetica", 8); c.drawString(12*mm, height-20*mm, "Imprimir al 100 %, sin ajustar, sin escalar. Calibraciones existentes no modificadas.")
    size = 57*mm
    positions = [(14*mm, height-84*mm), (78*mm, height-84*mm), (142*mm, height-84*mm),
                 (14*mm, height-151*mm), (78*mm, height-151*mm), (142*mm, height-151*mm)]
    for index, ((path, label), (x, y)) in enumerate(zip(stickers, positions), 1):
        c.drawImage(str(path), x, y, size, size, preserveAspectRatio=True, anchor="c", mask="auto")
        c.setFont("Helvetica", 7); c.drawCentredString(x+size/2, y-4*mm, f"{index}. {label} - nominal 57 mm")
    c.setLineWidth(.3); c.rect(14*mm, 17*mm, 50*mm, 20*mm)
    for step in range(0, 51, 5):
        x = (14+step)*mm; c.line(x, 17*mm, x, (20 if step%10 else 23)*mm)
        if step%10 == 0: c.setFont("Helvetica", 6); c.drawCentredString(x, 14*mm, str(step))
    c.setFont("Helvetica-Bold", 8); c.drawString(72*mm, 35*mm, "Control fisico posterior")
    c.setFont("Helvetica", 7)
    checks = ("[ ] Regla 50 mm exacta", "[ ] Sticker nominal 57 mm", "[ ] Sin halo gris",
              "[ ] Borde blanco uniforme", "[ ] Corte coincide con contorno", "[ ] Vista previa coincide")
    for row, text in enumerate(checks): c.drawString((72 if row<3 else 137)*mm, (30-(row%3)*5)*mm, text)
    c.setFont("Helvetica-Oblique", 6.5); c.drawRightString(width-12*mm, 10*mm, "CANDIDATOS P1 NO APROBADOS - requiere firma humana")
    c.showPage(); c.save()
    return output


